export const MESSAGES = { de, en };

function interpolate(text, params) {
  return text.replace(/\{(\w+)\}/g, (_, name) => (params && params[name] !== undefined ? String(params[name]) : `{${name}}`));
}

export function t(key, params) {
  const text = MESSAGES[state.lang][key] ?? MESSAGES.en[key] ?? key;
  return interpolate(text, params);
}

export function tOr(key, fallbackKey, params) {
  return MESSAGES[state.lang][key] !== undefined ? t(key, params) : t(fallbackKey, params);
}

export const localName = (entry) => entry.name[state.lang] || entry.name.en;
export const localText = (obj) => (obj ? obj[state.lang] || obj.en : '');

export function errorText(error) {
  const key = error && error.key ? error.key : 'internal_error';
  const params = (error && error.params) || {};
  return MESSAGES[state.lang][`error.${key}`] !== undefined ? t(`error.${key}`, params) : t('error.unknown', { key });
}

export function problemText(problem) {
  const known = MESSAGES[state.lang][`problem.${problem.code}`] !== undefined;
  return known ? t(`problem.${problem.code}`, problem) : t('problem.unknown', problem);
}

export function localiseDocument() {
  document.documentElement.lang = state.lang;
  document.documentElement.dataset.closeLabel = t('common.close');
}
